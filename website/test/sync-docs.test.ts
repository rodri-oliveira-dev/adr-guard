import { readFile } from 'node:fs/promises';
import { describe, expect, it } from 'vitest';

const generatedRoot = new URL('../src/content/docs/', import.meta.url);

describe('synchronized documentation', () => {
  it('localizes source badges from the destination locale', async () => {
    const [english, portuguese] = await Promise.all([
      readFile(new URL('product/vscode-extension.md', generatedRoot), 'utf8'),
      readFile(new URL('pt-br/product/vscode-extension.md', generatedRoot), 'utf8'),
    ]);

    expect(english).toContain('text: Source synced');
    expect(english).not.toContain('text: Fonte sincronizada');
    expect(portuguese).toContain('text: Fonte sincronizada');
    expect(portuguese).not.toContain('text: Source synced');
  });

  it('rewrites Marketplace image URLs to the GitHub Pages base path', async () => {
    const [english, portuguese] = await Promise.all([
      readFile(new URL('product/vscode-extension.md', generatedRoot), 'utf8'),
      readFile(new URL('pt-br/product/vscode-extension.md', generatedRoot), 'utf8'),
    ]);

    for (const markdown of [english, portuguese]) {
      expect(markdown).toContain('](/adr-guard/images/vscode/adr-list.png)');
      expect(markdown).not.toContain('raw.githubusercontent.com');
    }
  });

  it('generates bilingual MCP pages with verified publication and GitHub Packages backfill status', async () => {
    const routes = ['mcp', 'mcp-configuration', 'mcp-tools', 'mcp-security', 'mcp-release'];
    for (const route of routes) {
      const [english, portuguese] = await Promise.all([
        readFile(new URL(`product/${route}.md`, generatedRoot), 'utf8'),
        readFile(new URL(`pt-br/product/${route}.md`, generatedRoot), 'utf8'),
      ]);

      expect(english).toContain('Generated by scripts/sync-docs.mjs');
      expect(portuguese).toContain('Generated by scripts/sync-docs.mjs');
      expect(english).toContain('Source synced');
      expect(portuguese).toContain('Fonte sincronizada');
    }

    const [overview, overviewPt, release, releasePt] = await Promise.all([
      readFile(new URL('product/mcp.md', generatedRoot), 'utf8'),
      readFile(new URL('pt-br/product/mcp.md', generatedRoot), 'utf8'),
      readFile(new URL('product/mcp-release.md', generatedRoot), 'utf8'),
      readFile(new URL('pt-br/product/mcp-release.md', generatedRoot), 'utf8'),
    ]);
    // The checked-in Registry manifest is the publication baseline for both locales.
    const manifest = JSON.parse(await readFile(new URL('../../.mcp/server.json', import.meta.url), 'utf8')) as {
      version: string;
      packages: { version: string }[];
    };
    const version = manifest.version;
    expect(manifest.packages[0]?.version).toBe(version);

    expect(overview).toContain(`MCP \`${version}\` is published on`);
    expect(overviewPt).toContain(`O MCP \`${version}\` está publicado no`);
    for (const markdown of [overview, overviewPt]) {
      expect(markdown).toContain(`RodriOliveira.AdrGuard.Mcp/${version}`);
      expect(markdown).toContain(`mcp/v${version}`);
    }
    expect(overview).toContain('GitHub Packages remains a separately authenticated feed');
    expect(overviewPt).toContain('O GitHub Packages continua sendo um feed autenticado separado');
    expect(release).toContain(`published Registry version \`${version}\``);
    expect(releasePt).toContain(`versão \`${version}\` publicada no Registry`);
    expect(release).toContain('MCP GitHub Packages Backfill');
    expect(releasePt).toContain('MCP GitHub Packages Backfill');
    const tools = await readFile(new URL('product/mcp-tools.md', generatedRoot), 'utf8');
    expect(tools).toContain('list_adrs');
    expect(tools).toContain('verify_architecture');
  });
});
